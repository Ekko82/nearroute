"""Local credential detection reads synthetic files and never contacts a client."""

import json
import os
from pathlib import Path
import tempfile
import unittest
from unittest.mock import patch

import client_detection as detection


class LocalClientCredentialsTests(unittest.TestCase):
    def setUp(self):
        directory = tempfile.TemporaryDirectory(prefix="nearroute-client-config-")
        self.addCleanup(directory.cleanup)
        self.appdata = Path(directory.name)
        self.verge = self.appdata / "io.github.clash-verge-rev.clash-verge-rev"
        self.party = self.appdata / "mihomo-party"
        environment = patch.dict(os.environ, {"APPDATA": str(self.appdata)})
        environment.start()
        self.addCleanup(environment.stop)

    def write(self, path, content):
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content, encoding="utf-8")

    def credentials(self, controller="http://127.0.0.1:9097"):
        with patch.object(detection.os, "name", "nt"):
            return detection.local_client_credentials(controller)

    def verge_runtime(self, content):
        self.write(self.verge / "clash-verge.yaml", content)

    def test_generated_yaml_reads_only_top_level_endpoint_and_secret(self):
        self.verge_runtime(
            "# Generated by Clash Verge\n\nexternal-controller: 127.0.0.1:9097\n"
            "secret: 'fixture''s # key'\nproxies:\n- name: fixture\n"
            "  secret: subscription-password\n  server: example.invalid\n"
        )
        self.assertEqual(self.credentials(), "fixture's # key")
        self.assertEqual(self.credentials("http://localhost:9097/"), "fixture's # key")

    def test_json_and_double_quoted_generated_scalars(self):
        content = {"external-controller": "127.0.0.1:9097", "secret": 'fixture"key'}
        self.verge_runtime(json.dumps(content))
        self.assertEqual(self.credentials(), 'fixture"key')
        self.verge_runtime('external-controller: "127.0.0.1:9097" # bind\nsecret: "fixture\\u0023key"\n')
        self.assertEqual(self.credentials(), "fixture#key")

    def test_no_secret_is_shared_across_ports_families_paths_or_remote_hosts(self):
        self.verge_runtime("external-controller: 127.0.0.1:9097\nsecret: private-fixture\n")
        for address in (
            "http://127.0.0.1:9090", "http://[::1]:9097", "http://192.168.1.1:9097",
            "http://localhost:9097/api", "http://user:pass@localhost:9097",
            "http://localhost:9097?key=fixture", "https://localhost:9097",
        ):
            with self.subTest(address=address):
                self.assertEqual(self.credentials(address), "")

    def test_wildcard_bind_matches_only_its_loopback_family(self):
        self.verge_runtime("external-controller: 0.0.0.0:9097\nsecret: ipv4-fixture\n")
        self.assertEqual(self.credentials(), "ipv4-fixture")
        self.assertEqual(self.credentials("http://[::1]:9097"), "")
        self.verge_runtime("external-controller: '[::]:9097'\nsecret: ipv6-fixture\n")
        self.assertEqual(self.credentials("http://[::1]:9097"), "ipv6-fixture")
        self.assertEqual(self.credentials(), "")

    def test_disabled_runtime_does_not_reuse_baseline_or_subscription_credentials(self):
        self.verge_runtime("external-controller: ''\nsecret: active-fixture\n")
        self.write(self.verge / "config.yaml", "external-controller: 127.0.0.1:9097\nsecret: stale-fixture\n")
        self.write(self.verge / "profiles" / "fixture.yaml", "external-controller: 127.0.0.1:9097\nsecret: profile-fixture\n")
        self.assertEqual(self.credentials(), "")

    def test_ambiguous_or_unsupported_yaml_is_rejected(self):
        cases = (
            "external-controller: 127.0.0.1:9097\nsecret: first\nsecret: second\n",
            "external-controller: 127.0.0.1:9097\nsecret: first\n'secret': second\n",
            "external-controller: 127.0.0.1:9097\nsecret: &value first\n",
            "external-controller: 127.0.0.1:9097\nsecret: *value\n",
            "external-controller: 127.0.0.1:9097\nsecret: !!str first\n",
            "external-controller: 127.0.0.1:9097\nsecret: |\n  multiline\n",
            "external-controller: 127.0.0.1:9097\nsecret: first\n  continuation\n",
            "external-controller: 127.0.0.1:9097\nsecret: first\n<<: *other\n",
            "external-controller: 127.0.0.1:9097\nsecret: first\n---\nsecret: second\n",
            "- external-controller: wrong\nexternal-controller: 127.0.0.1:9097\nsecret: first\n",
            "external-controller: 127.0.0.1:9097\nsecret: 12345\n",
        )
        for content in cases:
            with self.subTest(content=content):
                self.verge_runtime(content)
                self.assertEqual(self.credentials(), "")

    def test_duplicate_json_credentials_are_rejected(self):
        self.verge_runtime('{"external-controller":"127.0.0.1:9097","secret":"first","secret":"second"}')
        self.assertEqual(self.credentials(), "")

    def test_both_party_names_use_the_official_runtime_directory(self):
        self.write(self.party / "config.yaml", "diffWorkDir: false\n")
        self.write(self.party / "work" / "config.yaml", "external-controller: 127.0.0.1:9097\nsecret: party-fixture\n")
        self.write(self.party / "mihomo.yaml", "external-controller: 127.0.0.1:9097\nsecret: stale-fixture\n")
        self.assertEqual(self.credentials(), "party-fixture")

    def test_party_uses_selected_work_directory_without_scanning_other_profiles(self):
        self.write(self.party / "config.yaml", "diffWorkDir: true\n")
        self.write(self.party / "profile.yaml", "current: selected-fixture\nitems:\n- id: old-fixture\n")
        self.write(self.party / "work" / "config.yaml", "external-controller: 127.0.0.1:9097\nsecret: stale-common\n")
        self.write(self.party / "work" / "old-fixture" / "config.yaml", "external-controller: 127.0.0.1:9097\nsecret: stale-profile\n")
        self.write(self.party / "work" / "selected-fixture" / "config.yaml", "external-controller: 127.0.0.1:9097\nsecret: selected-secret\n")
        self.assertEqual(self.credentials(), "selected-secret")
        self.write(self.party / "profile.yaml", "current: '../old-fixture'\n")
        self.assertEqual(self.credentials(), "")

    def test_conflicting_client_secrets_for_same_endpoint_are_not_guessed(self):
        self.verge_runtime("external-controller: 127.0.0.1:9097\nsecret: verge-fixture\n")
        self.write(self.party / "config.yaml", "diffWorkDir: false\n")
        self.write(self.party / "work" / "config.yaml", "external-controller: 127.0.0.1:9097\nsecret: party-fixture\n")
        self.assertEqual(self.credentials(), "")

    def test_remote_or_malformed_runtime_endpoint_does_not_export_its_secret(self):
        for endpoint in ("192.168.1.1:9097", "http://127.0.0.1:9097", "127.0.0.1:9097/api", "user@127.0.0.1:9097", "0.0.0.0:9097?key=fixture"):
            with self.subTest(endpoint=endpoint):
                self.verge_runtime(f"external-controller: '{endpoint}'\nsecret: private-fixture\n")
                self.assertEqual(self.credentials(), "")


if __name__ == "__main__":
    unittest.main()
